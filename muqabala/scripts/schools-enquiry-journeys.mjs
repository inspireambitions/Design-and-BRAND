// Uses only the explicitly guarded staging fixture from schools-staging-qa.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {randomUUID} from 'node:crypto';
import {mkdir,writeFile} from 'node:fs/promises';
import {login} from './schools-staging-qa.mjs';
import {qaStage} from './schools-qa-errors.mjs';

const require=createRequire(import.meta.url);
const {chromium}=require(process.env.SCHOOLS_QA_PLAYWRIGHT);
const origin='http://localhost:3110';
const out='output/schools-enquiry-20260916';
await mkdir(out,{recursive:true});
const checks=[];
const check=result=>{if(result.error)throw new Error(result.error.message);return result.data;};
qaStage('student login');const student=await login('student');
qaStage('educator login');const educator=await login('educator');
qaStage('founder login');const founder=await login('founder');
const f=student.fixture, admin=student.admin;
qaStage('create isolated cohort');
const cohort=check(await admin.rpc('schools_manage_action',{actor:f.users.admin.id,operation:'cohort',device:'server',payload:{institutionId:f.institutions[0],name:'Synthetic enquiry release QA '+new Date().toISOString()}}));
qaStage('assign adviser');check(await admin.rpc('schools_manage_action',{actor:f.users.admin.id,operation:'assign_educator',device:'server',payload:{cohortId:cohort.id,userId:f.users.educator.id}}));
check(await admin.from('schools_cohort_members').insert({cohort_id:cohort.id,student_user_id:f.users.student.id,display_name:'Synthetic release learner',adult_confirmed_at:new Date().toISOString()}));
qaStage('create assignment');const questionIds=check(await admin.from('schools_assignment_questions').select('question_version_id').eq('assignment_id',f.assignments[0]).order('question_index')).map(q=>q.question_version_id);
const assignment=check(await admin.rpc('schools_manage_action',{actor:f.users.educator.id,operation:'assignment',device:'server',payload:{cohortId:cohort.id,roleId:'Student placement',questionIds,dueAt:new Date(Date.now()+7*86400000).toISOString()}}));
qaStage('launch browser');const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[];
const makePage=async(identity,width=1280)=>{
  const context=await browser.newContext({viewport:{width,height:900}});
  if(identity)await context.addCookies(identity.cookies);
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));return {context,page};
};
try{
  qaStage('landing');const {page:landing}=await makePage(null,390);
  await landing.goto(origin+'/schools');
  await landing.getByRole('heading',{name:'Enquire about a school pilot',exact:true}).waitFor();
  assert.equal(await landing.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await landing.screenshot({path:out+'/landing-mobile.png',fullPage:true});
  checks.push('Mobile public page: clear enquiry heading, no horizontal overflow');

  qaStage('student journey');const {page:learner}=await makePage(student,390);
  await learner.goto(origin+'/schools/home');
  await learner.waitForURL('**/schools/me');
  checks.push('Student sign-in destination selects student home');
  await learner.goto(origin+'/schools/me/'+assignment.id);
  const answers=['Our class project was due on Friday. I made a list of remaining tasks and agreed responsibilities with my group. We finished on time.','Our project materials were late. I found another supplier and asked my tutor to check the order. Our group completed the project.','My tutor asked for clearer notes. I added headings and asked a classmate to check them. We could follow the notes.'];
  const fields=learner.getByRole('textbox',{name:'Your answer',exact:true});
  await fields.first().fill(answers[0]);
  await learner.getByRole('status').filter({hasText:'Draft saved.'}).waitFor({timeout:45000});
  await learner.reload();assert.equal(await fields.first().inputValue(),answers[0]);
  checks.push('Student autosave survives refresh');
  const drafts=check(await educator.session.from('schools_assignment_attempts').select('id').eq('assignment_id',assignment.id));
  assert.equal(drafts.length,0);checks.push('Adviser cannot read student draft');
  for(let i=1;i<3;i++)await fields.nth(i).fill(answers[i]);
  await learner.getByRole('button',{name:'Save draft',exact:true}).click();
  await learner.getByRole('status').filter({hasText:'Draft saved.'}).waitFor();
  let lost=false;
  await learner.route('**/api/schools',async route=>{
    if(route.request().postDataJSON()?.operation==='submit'&&!lost){lost=true;const response=await route.fetch();assert(response.ok());await route.abort('failed');}
    else await route.continue();
  });
  await learner.getByRole('button',{name:'Submit answers',exact:true}).click();
  await learner.getByRole('alert').first().waitFor();
  assert.equal(await fields.first().inputValue(),answers[0]);
  await learner.getByRole('button',{name:'Submit answers',exact:true}).click();
  await learner.getByRole('heading',{name:'Your answers are saved',exact:true}).waitFor();
  const submitted=check(await student.session.from('schools_assignment_attempts').select('id,answers').eq('assignment_id',assignment.id).eq('status','submitted'));
  assert.equal(submitted.length,1);const attempt=submitted[0];
  checks.push('Lost submission response preserves text; retry creates exactly one submission');
  // A deterministic fixture tests report rendering, not AI quality.
  const claim=randomUUID();check(await admin.rpc('schools_claim_feedback',{attempt:attempt.id,claim}));
  const detail=answers.map((answer,questionIndex)=>({questionIndex,improvement:'Describe one detail about the outcome.',elements:[0,1,2,3].map(i=>({id:'e'+i,present:i<2,supportingText:i<2?answer:'',confidence:'medium',start:i<2?0:null,end:i<2?answer.length:null}))}));
  assert(check(await admin.rpc('schools_store_feedback',{attempt:attempt.id,claim,model_name:'synthetic-ui-fixture',contract:'synthetic-ui-fixture',feedback:{questions:detail},detail,input_count:0,output_count:0})));
  qaStage('adviser journey');const {page:adviser}=await makePage(educator);
  await adviser.goto(origin+'/schools/home');await adviser.waitForURL('**/schools/cohorts');
  checks.push('Adviser sign-in destination selects adviser cohorts');
  await adviser.goto(origin+'/schools/cohorts/'+cohort.id);
  await adviser.screenshot({path:out+'/adviser-cohort.png',fullPage:true});
  await adviser.goto(origin+'/schools/cohorts/'+cohort.id+'/review?attempt='+attempt.id);
  const comment='Synthetic adviser check: please add the final project outcome.';
  await adviser.getByLabel('Your view',{exact:true}).selectOption('needs_more');
  await adviser.getByLabel('Comment, up to 280 characters',{exact:true}).fill(comment);
  await adviser.getByRole('button',{name:'Save review',exact:true}).click();
  await adviser.getByRole('status').filter({hasText:'Review saved.'}).waitFor();
  await adviser.getByRole('button',{name:'Undo',exact:true}).click();
  await adviser.getByRole('status').filter({hasText:'Previous review restored.'}).waitFor();
  assert.equal(await adviser.getByLabel('Comment, up to 280 characters',{exact:true}).inputValue(),'');
  await adviser.getByLabel('Comment, up to 280 characters',{exact:true}).fill(comment);
  await adviser.getByRole('button',{name:'Save review',exact:true}).click();
  await adviser.getByRole('status').filter({hasText:'Review saved.'}).waitFor();
  await adviser.screenshot({path:out+'/adviser-review.png',fullPage:true});
  checks.push('Adviser reads submission, saves review, undoes it, and saves final comment');
  await learner.goto(origin+'/schools/me/reports/'+attempt.id);
  await learner.getByText(comment,{exact:true}).waitFor();
  await learner.screenshot({path:out+'/student-report.png',fullPage:true});
  checks.push('Student report shows feedback fixture and the final adviser comment');
  const other=await login('otherStudent');
  const {page:outsider}=await makePage(other);
  const forbidden=await outsider.goto(origin+'/schools/me/reports/'+attempt.id);
  assert.equal(forbidden.status(),404);checks.push('Different student receives 404 for the report');
  const {page:owner}=await makePage(founder);
  await owner.goto(origin+'/schools/founder');
  await owner.getByRole('heading',{name:'Pilot enquiries',exact:true}).waitFor();
  await owner.screenshot({path:out+'/founder-inbox.png',fullPage:true});
  checks.push('Founder enquiry inbox renders');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({checks,syntheticFeedback:true,physicalDevice:false}));
  await writeFile(out+'/results.json',JSON.stringify({checkedAt:new Date().toISOString(),origin,checks,errors,cohortId:cohort.id,assignmentId:assignment.id,attemptId:attempt.id,syntheticFeedback:true,physicalDevice:false},null,2)+'\n');
}finally{await browser.close();}
